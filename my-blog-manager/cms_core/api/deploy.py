# ☁️ EdgeOne 源码接口：同步源代码到 GitHub 触发仓库
@router.post("/source")
async def sync_source_to_edgeone(request: Request):
    try:
        payload = await request.json()
        blog_path = payload.get("blogPath", "").strip()

        if not blog_path or not os.path.isfile(os.path.join(blog_path, "package.json")):
            return {"success": False, "message": "无效的 yukiBlogs 前端路径！"}

        # 读取配置
        if not os.path.exists(CONFIG_FILE):
            return {"success": False, "message": "未找到配置文件，请先点击保存！"}

        with open(CONFIG_FILE, "r", encoding="utf-8") as f:
            config = json.load(f)

        source_repo = config.get("sourceRepoUrl", "").strip()
        source_branch = config.get("sourceBranch", "main").strip()

        if not source_repo:
            return {"success": False, "message": "源码仓库地址为空，无法同步！"}

        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._/-]*", source_branch) or ".." in source_branch:
            return {"success": False, "message": "源码分支名不合法！"}

        # Always refresh the frontend tree from the manager before committing.
        synced, sync_message = sync_blog_tree(blog_path)
        if not synced:
            return {"success": False, "message": f"前端镜像失败: {sync_message}"}

        # 1. 添加所有代码改动
        subprocess.run(["git", "add", "."], cwd=blog_path, check=True)

        # 2. 提交代码 (这里加入容错)
        subprocess.run(
            ["git", "commit", "-m", "Auto sync source code for EdgeOne"],
            cwd=blog_path,
            capture_output=True,
            text=True,
        )

        # 🌟 终极杀招：强行绑定 源码仓库专属私钥，无视 Windows 智障路由！
        ssh_dir = os.path.expanduser("~/.ssh")
        # 把 Windows 的反斜杠强制替换为正斜杠，防止 Git 识别错误
        priv_key_path = os.path.join(ssh_dir, "id_ed25519_source").replace("\\", "/")

        # 组装环境变量，用 GIT_SSH_COMMAND 强行逼迫 Git 使用这把钥匙
        custom_env = os.environ.copy()
        custom_env["GIT_SSH_COMMAND"] = f'ssh -i "{priv_key_path}" -o IdentitiesOnly=yes -o StrictHostKeyChecking=accept-new'

        # 3. 推送 (携带我们强行塞进去的钥匙环境变量)
        push_process = subprocess.run(
            ["git", "push", source_repo, f"HEAD:{source_branch}"],
            cwd=blog_path,
            capture_output=True,
            text=True,
            encoding='utf-8',
            env=custom_env  # 👈 就是这里！把钥匙按在 Git 脸上！
        )

        # 判断是否成功
        if push_process.returncode != 0 and "Everything up-to-date" not in push_process.stderr:
            return {"success": False, "message": f"源码同步失败:\n{push_process.stderr}"}

        return {"success": True, "message": "☁️ 源码已成功送达 GitHub，EdgeOne 构建已触发！"}

    except Exception as e:
        return {"success": False, "message": f"源码同步引擎异常: {str(e)}"}
